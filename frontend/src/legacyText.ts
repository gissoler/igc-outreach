const KEYS = new Set(['message', 'title', 'provider', 'summary', 'label', 'note', 'reason', 'why', 'headline', 'items', 'decision', 'error', 'kind_label', 'stageLabel', 'detailText']);
const SPANISH = /[áéíóúñ¿¡]|\b(de|del|con|sin|para|que|candidatos|registros?|fuente|personas|avisos|consulta)\b/i;

export function legacyText(s: string): string {
  if (!s || !SPANISH.test(s)) return s;
  let out = s;
  for (const [es, en] of PAIRS) if (out.includes(es)) out = out.split(es).join(en);
  return out
    .replace(/ (?:respondió|returned) con (\d+) (?:registros?|records?) en (\d+) ms/g, (_m, n, ms) => ` returned ${n} record${n === '1' ? '' : 's'} in ${ms} ms`)
    .replace(/\b(\d+) registros?\b/g, (_m, n) => `${n} record${n === '1' ? '' : 's'}`)
    .replace(/ en (\d+(?:[.,]\d+)?) (ms|s)\b/g, ' in $1 $2')
    .replace(/\bcandidatos\b/g, 'candidates').replace(/\bpersonas verificadas\b/g, 'verified people').replace(/\bpáginas públicas\b/g, 'public pages');
}

/** Recorre una respuesta y traduce solo campos de texto de interfaz (nunca citas ni URLs). */
export function legacyDeep<T>(value: T, key = ''): T {
  if (typeof value === 'string') return (KEYS.has(key) ? maskBrands(legacyText(value)) : BRAND_KEYS.has(key) ? maskBrands(value) : value) as T;
  if (Array.isArray(value)) return value.map((v) => legacyDeep(v, key === 'items' ? 'items' : key)) as T;
  if (value && typeof value === 'object') {
    const out: Record<string, unknown> = {};
    for (const [k, v] of Object.entries(value as Record<string, unknown>)) out[k] = k === 'quote' || k === 'url' ? v : legacyDeep(v, k);
    return out as T;
  }
  return value;
}
